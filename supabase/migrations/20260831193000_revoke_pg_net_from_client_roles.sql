-- ===========================================================================
-- SECONDO MOTIVO: la revoca giusta fermerebbe le notifiche
-- ===========================================================================
-- L'ACL reale di `net.http_post` e' `=X/supabase_admin`, dove il grantee vuoto
-- prima di `=` significa **PUBLIC**. `anon` non ha nessun grant diretto: eredita
-- da PUBLIC. Quindi la revoca corretta sarebbe `FROM PUBLIC`, non `FROM anon`.
--
-- Ma nella stessa ACL non compare `postgres`, ed e' `postgres` a far girare il
-- job cron del dispatcher. `postgres` puo' chiamare `net.http_post` **solo**
-- tramite PUBLIC. Revocare da PUBLIC senza prima concedere esplicitamente a
-- `postgres` fermerebbe le notifiche push - e anche quel GRANT richiede di
-- essere owner, cioe' `supabase_admin`.
--
