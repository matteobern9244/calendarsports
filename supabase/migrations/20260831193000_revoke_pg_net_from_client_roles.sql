-- Le dodici funzioni di pg_net e lo schema `net` appartengono a
-- `supabase_admin`. Le migration girano come `postgres`, che **non e'
-- superuser e non e' membro di `supabase_admin`** (verificato con
-- `pg_has_role`). In PostgreSQL un REVOKE eseguito da chi non e' owner ne' ha
-- GRANT OPTION emette un warning e prosegue: nessun errore, nessun effetto.
--
-- E' il modo peggiore in cui una migration puo' sbagliare. Applicata, sembra
-- riuscita: il file finisce nella cartella, il changelog dichiara il problema
-- chiuso, e il privilegio e' esattamente dov'era. Lo si vede solo rileggendo i
